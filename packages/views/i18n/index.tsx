const dictionaries: Record<Locale, typeof en> = {
  en,
  zh,
  ja: en,
  ko: en,
  es: en,
  fr: en,
  de: en,
  pt: en,
};

export type AppDict = typeof en;

function getCookieLocale(): Locale | null {
  if (typeof document === "undefined") return null;
  const match = document.cookie.match(/(?:^|;\s*)multica-locale=([\w-]+)/);
  const locale = match?.[1];
  return locale && isLocale(locale) ? locale : null;
}

function detectLocaleFromNavigator(): Locale {
  if (typeof navigator === "undefined") return "en";
  const raw = navigator.language.toLowerCase();
  if (raw.startsWith("zh")) return "zh";
  if (raw.startsWith("ja")) return "ja";
  if (raw.startsWith("ko")) return "ko";
  if (raw.startsWith("es")) return "es";
  if (raw.startsWith("fr")) return "fr";
  if (raw.startsWith("de")) return "de";
  if (raw.startsWith("pt")) return "pt";
  return "en";
}

function toIntlLocale(locale: Locale): string {
  switch (locale) {
    case "zh":
      return "zh-CN";
    case "ja":
      return "ja-JP";
    case "ko":
      return "ko-KR";
    case "es":
      return "es-ES";
    case "fr":
      return "fr-FR";
    case "de":
      return "de-DE";
    case "pt":
      return "pt-BR";
    default:
      return "en-US";
  }
}

export function useAppI18n() {
  const locale = useLocaleStore((s) => s.locale);
  const setLocale = useLocaleStore((s) => s.setLocale);

  return {
    locale,
    locales,
    localeLabels,
    setLocale,
    t: dictionaries[locale],
    formatDate: (value: string | number | Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(toIntlLocale(locale), options).format(new Date(value)),
    formatDateTime: (value: string | number | Date, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(toIntlLocale(locale), options).format(new Date(value)),
  };
}

export function AppLocaleSync() {
  const locale = useLocaleStore((s) => s.locale);
  const setLocale = useLocaleStore((s) => s.setLocale);

  useEffect(() => {
    const cookieLocale = getCookieLocale();
    setLocale(cookieLocale ?? detectLocaleFromNavigator());
    // Read persisted or browser locale once at boot.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [setLocale]);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.cookie = `${COOKIE_NAME}=${locale}; path=/; max-age=${COOKIE_MAX_AGE}; SameSite=Lax`;
  }, [locale]);

  return null;
}
